import { ContractAuditResponse, AIAuditReport } from "../types";

export function generateMarkdownReport(audit: ContractAuditResponse): string {
    const criticalCount = audit.findings.filter(f => f.severity === 'CRITICAL').length;
    const highCount = audit.findings.filter(f => f.severity === 'HIGH').length;
    const mediumCount = audit.findings.filter(f => f.severity === 'MEDIUM').length;
    const lowCount = audit.findings.filter(f => f.severity === 'LOW').length;
    const infoCount = audit.findings.filter(f => f.severity === 'INFORMATIONAL').length;

    return `
# Smart Contract Audit Report

**Generated:** ${new Date(audit.analyzedAt).toLocaleString()}
**Contract:** ${audit.metadata.name || 'Unknown'}

---

## Executive Summary

| Metric | Value |
|--------|-------|
| **Risk Level** | ${audit.verdict.overall} |
| **Audit Score** | ${audit.verdict.auditScore}/100 |
| **Recommendation** | ${audit.verdict.recommendation} |
| **Confidence** | ${Math.round(audit.verdict.confidence * 100)}% |
| **Compiler** | ${audit.metadata.pragmaVersion || 'Unknown'} |

### Summary
${audit.verdict.summary}

---

## Findings Overview

| Severity | Count |
|----------|-------|
| Critical | ${criticalCount} |
| High | ${highCount} |
| Medium | ${mediumCount} |
| Low | ${lowCount} |
| Informational | ${infoCount} |
| **Total** | **${audit.findings.length}** |

---

## Key Risk Factors

${audit.verdict.keyFactors.map(f => `- ${f}`).join('\n')}

---

## Detailed Findings

${audit.findings.map((finding, index) => `
### ${index + 1}. ${finding.title}

- **ID:** ${finding.id}
- **Severity:** ${finding.severity}
- **Category:** ${finding.category}
${finding.location.line ? `- **Location:** Line ${finding.location.line}` : ''}
${finding.swcId ? `- **SWC:** ${finding.swcId}` : ''}

**Description:**
${finding.description}

**Recommendation:**
${finding.recommendation}
`).join('\n---\n')}

---

## Compliance & Standards

### OpenZeppelin Compliance
- **Score:** ${audit.ozCompliance.complianceScore}/100
- **Version:** ${audit.ozCompliance.version}

### Token Compliance
${audit.findings.filter(f => f.category === 'TOKEN_COMPLIANCE').length === 0 ? '- No compliance issues detected' : '- See detailed findings for compliance issues'}

---

## Gas Optimization

**Estimated Savings:** ~${audit.gasReport.estimatedSavings} gas
**Total Optimizations Found:** ${audit.gasReport.totalOptimizations}

${audit.gasReport.topOptimizations.length > 0
  ? audit.gasReport.topOptimizations.map(opt => `- **${opt.title}**: ${opt.savings} (${opt.count} occurrence${opt.count > 1 ? 's' : ''})`).join('\n')
  : '- No specific optimizations identified'}

---

## Contract Metadata

- **Lines of Code:** ${audit.metadata.lineCount}
- **Functions:** ${audit.metadata.functionCount}
- **Contracts:** ${audit.metadata.contractCount}
- **License:** ${audit.metadata.licenseIdentifier || 'Not specified'}

---

*Verified by Smart Contract Audit Agent*
`;
}

/**
 * Generate markdown section for AI-enhanced audit report
 */
export function generateAIMarkdownSection(aiReport: AIAuditReport): string {
    return `

---

## AI-Enhanced Analysis

*Generated by: ${aiReport.generatedBy}*
*Generated at: ${new Date(aiReport.generatedAt).toLocaleString()}*

### Executive Summary

${aiReport.executiveSummary}

### Detailed Analysis

${aiReport.detailedAnalysis}

### Security Recommendations

${aiReport.securityRecommendations.map((r, i) => `${i + 1}. ${r}`).join('\n')}

### Gas Optimization Suggestions

${aiReport.gasOptimizationSuggestions.map(s => `- ${s}`).join('\n')}

### Code Quality Assessment

${aiReport.codeQualityAssessment}

### Compliance Notes

${aiReport.complianceNotes}

### Overall Assessment

${aiReport.overallAssessment}

---

*AI analysis provided by ${aiReport.generatedBy.split('/')[1] || aiReport.generatedBy}*
`;
}
